export function getTippingRuleForCountry(countryCode?: string | null): TippingCultureRule & { poorPercent: number; poorLabel: string; poorDescription: string } {
  if (!countryCode) return { ...DEFAULT_TIPPING_RULE, poorPercent: 0, poorLabel: 'Poor (0%)', poorDescription: 'No tip left for poor service.' };
  const upper = countryCode.trim().toUpperCase();
  const rule = COUNTRY_TIPPING_DATABASE[upper] || DEFAULT_TIPPING_RULE;
  return {
    ...rule,
    poorPercent: typeof rule.poorPercent === 'number' ? rule.poorPercent : (rule.isTippingCustomary && rule.minPercent >= 15 ? 10 : 0),
    poorLabel: rule.poorLabel || 'Poor Service',
    poorDescription: rule.poorDescription || 'Baseline for sub-par service.',
  };
}
